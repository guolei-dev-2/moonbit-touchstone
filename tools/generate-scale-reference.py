"""Emit independent Fraction oracle fixtures for finite binary64 range bugs.

No floating complex division or Gauss-Jordan is used to produce expectations.
Run with fresh --test and --receipt paths; the checked-in generated test is
numeric_scale_reference_test.mbt. All inputs are project-generated synthetic data.
"""
import argparse,hashlib,json,math
from fractions import Fraction as F
from pathlib import Path
p=argparse.ArgumentParser(description=__doc__)
p.add_argument('--test',type=Path,required=True);p.add_argument('--receipt',type=Path,required=True)
a=p.parse_args()
if a.test.exists() or a.receipt.exists():p.error('use fresh output paths')
def fc(z):return F(z[0]),F(z[1])
def mul(a,b):return a[0]*b[0]-a[1]*b[1],a[0]*b[1]+a[1]*b[0]
def sub(a,b):return a[0]-b[0],a[1]-b[1]
def div(a,b):
 d=b[0]*b[0]+b[1]*b[1]
 return (a[0]*b[0]+a[1]*b[1])/d,(a[1]*b[0]-a[0]*b[1])/d
def fl(z):return tuple(float(v) for v in z)
def lit(x):
 s=repr(x)
 if 'e' in s and '.' not in s.split('e')[0]:s=s.replace('e','.0e')
 return s
def tup(values):return '('+', '.join(lit(x) for x in values)+')'
cases=[];reject=[]
exponents=[-1074,-1022,-600,0,600,1023]
for ea in exponents:
 for eb in exponents:
  x=(math.ldexp(1.,ea),math.ldexp(.75,ea));y=(math.ldexp(1.,eb),math.ldexp(-.5,eb))
  try:q=fl(div(fc(x),fc(y)))
  except OverflowError:reject.append((*x,*y));continue
  cases.append((*x,*y,*q))
for x,y in [((1e308,1e308),(1.,1.)),((1.7e308,0.),(.9,.9)),((5e-324,5e-324),(1.5,1.5)),
 ((1.,1.),(1e-308,1e-308)),((1e-308,1e-308),(1.,-1.)),((1.3e308,1.3e308),(1.3e308,1.3e308))]:
 cases.append((*x,*y,*fl(div(fc(x),fc(y)))))
matrices=[]
for e in [-1022,-600,0,600,1023]:
 scale=math.ldexp(1.,e)
 z=[(scale,scale),(.5*scale,-.25*scale),(-.25*scale,.5*scale),(scale,-.5*scale)]
 m=list(map(fc,z));det=sub(mul(m[0],m[3]),mul(m[1],m[2]))
 inv=[div(m[3],det),div((-m[1][0],-m[1][1]),det),div((-m[2][0],-m[2][1]),det),div(m[0],det)]
 matrices.append((z,[fl(v) for v in inv]))
lines=['// Generated by tools/generate-scale-reference.py using exact fractions.Fraction.',
 '///|','test "Fraction oracle covers finite and overflowing complex quotients across binary exponents" {',
 '  let cases : Array[(Double, Double, Double, Double, Double, Double)] = [']
lines += ['    '+tup(c)+',' for c in cases]
lines += ['  ]','  for (ar, ai, br, bi, er, ei) in cases {',
 '    let z = @touchstone.complex(ar, im=ai).divide(@touchstone.complex(br, im=bi))',
 '    assert_true((z.re-er).abs() <= (er.abs()*3.0e-14).max(2.0e-323))',
 '    assert_true((z.im-ei).abs() <= (ei.abs()*3.0e-14).max(2.0e-323))','  }',
 '  let overflow : Array[(Double, Double, Double, Double)] = [']
lines += ['    '+tup(c)+',' for c in reject]
lines += ['  ]','  for (ar, ai, br, bi) in overflow {',
 '    try @touchstone.complex(ar, im=ai).divide(@touchstone.complex(br, im=bi)) catch {',
 '      _ => ()','    } noraise {','      _ => fail("nonrepresentable quotient accepted")','    }','  }','}',
 '///|','test "Fraction adjugate oracle checks scaled complex two by two inverse" {']
for z,inv in matrices:
 lines += ['  {','    let input = ['+', '.join('@touchstone.complex('+lit(v[0])+', im='+lit(v[1])+')' for v in z)+']',
 '    let expected : Array[(Double,Double)] = ['+', '.join(tup(v) for v in inv)+']',
 '    let actual = @touchstone.invert_matrix(2,input)',
 '    for i, (er,ei) in expected {',
 '      assert_true((actual[i].re-er).abs() <= (er.abs()*4.0e-14).max(2.0e-323))',
 '      assert_true((actual[i].im-ei).abs() <= (ei.abs()*4.0e-14).max(2.0e-323))','    }','  }']
lines += ['}']
a.test.write_text('\n'.join(lines)+'\n',encoding='utf-8')
a.receipt.write_text(json.dumps(dict(oracle='exact fractions.Fraction, rounded only at final float(); inverse uses exact2x2adjugate, not Gauss-Jordan',
 divisionFinite=cases,divisionOverflow=reject,inverseCases=matrices,testSHA256=hashlib.sha256(a.test.read_bytes()).hexdigest()),indent=2)+'\n',encoding='utf-8')
print(json.dumps(dict(finiteQuotients=len(cases),overflowQuotients=len(reject),exactMatrixInverses=len(matrices))))
