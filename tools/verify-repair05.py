"""Targeted RF/limits checks after numeric primitive repair, synthetic inputs.

Uses scikit-rf for independent mixed-mode/cascade/DUT expectations and analytic
boundary examples. Does not rerun historical suites or download vendor inputs.
"""
import argparse,hashlib,json,subprocess
from pathlib import Path
import numpy as np
import skrf as rf
ROOT=Path(__file__).resolve().parents[1]
p=argparse.ArgumentParser(description=__doc__);p.add_argument('--evidence',type=Path,required=True);args=p.parse_args()
if args.evidence.exists():p.error('choose a fresh receipt')
host=subprocess.Popen(['node','tools/oracle-host.mjs'],cwd=ROOT,stdin=subprocess.PIPE,stdout=subprocess.PIPE,text=True,encoding='utf-8')
rng=np.random.default_rng(20261028);raw=[];checks=[]
def text(net):
 n=net.nports;lines=['[Version] 2.1','# Hz S RI R 50',f'[Number of Ports] {n}',f'[Number of Frequencies] {len(net.f)}',
 '[Reference] '+' '.join(format(x.real,'.17g') for x in net.z0[0])]
 if n==2:lines+=['[Two-Port Data Order] 12_21']
 lines+=['[Network Data]']
 for f,m in zip(net.f,net.s):lines+=[' '.join([format(f,'.17g')]+[format(v,'.17g') for z in m.ravel() for v in [z.real,z.imag]])]
 return '\n'.join(lines+['[End]'])+'\n'
def ask(t,command,reject=False,left='',right='',**kw):
 q=dict(text=t,left=left,right=right,options=dict(command=command,**kw))
 host.stdin.write(json.dumps(q)+'\n');host.stdin.flush();line=host.stdout.readline();assert line,'bridge stopped'
 r=json.loads(line);raw.append(dict(query=q,response=r));assert r['ok']!=reject,r
 return r.get('result')
def mat(d):return np.array([[complex(z['re'],z['im']) for z in row] for row in d['values']]).reshape(-1,d['ports'],d['ports'])
def close(got,want,label):
 np.testing.assert_allclose(got,want,rtol=2e-10,atol=2e-12)
 checks.append(dict(label=label,maxAbsoluteError=float(np.max(np.abs(np.asarray(got)-want)))))
def net(refs):
 n=len(refs);s=(rng.normal(size=(2,n,n))+1j*rng.normal(size=(2,n,n)))*.04
 if n==2:s[:,1,0]+=.65;s[:,0,1]+=.3
 # Explicit f-by-port shape avoids the nfreq==nports ambiguity of a 1-D z0.
 return rf.Network(f=[1.,2.],s=s,z0=np.tile(np.asarray(refs),(2,1)))
failure=None
try:
 for refs,pairs in [([50,75,50],[[2,0]]),([35,35,110,110],[[2,3],[1,0]])]:
  a=net(refs);order=sum(pairs,[])+[i for i in range(len(refs)) if i not in sum(pairs,[])]
  expected=a.copy();expected.renumber(order,list(range(len(refs))));expected.se2gmm(len(pairs))
  out=ask(text(a),'mixed',pairs=pairs)
  close(mat(out['network']),expected.s,'independent mixed mode and nonsequential ports')
  close(out['network']['reference_ohms'],expected.z0[0].real,'modal reference ohms')
 for refs in [(35.,75.,90.,110.),(.5,2.,3.,5.)]:
  outerL,innerL,innerR,outerR=refs
  left=net([outerL,innerL]);dut=net([innerL,innerR]);right=net([innerR,outerR])
  expected=left**dut
  out=ask(text(left),'cascade',right=text(dut))
  close(rf.Network.from_string(out['text']).s,expected.s,'cascade at distinct inner/outer references')
  measured=left**dut**right
  out=ask(text(measured),'deembed',left=text(left),right=text(right))
  recovered=rf.Network.from_string(out['text'])
  close(recovered.s,dut.s,'two-sided independently generated DUT')
  close(recovered.z0[0].real,dut.z0[0].real,'deembedded DUT references')
 # Rejection semantics, not numeric golden generated by the implementation.
 a=net([50,50]);b=net([75,50]);ask(text(a),'cascade',right=text(b),reject=True)
 ask(text(net([50,75,50])),'mixed',pairs=[[0,1]],reject=True)
 singular=rf.Network(f=[1,2],s=np.array([[[0,0],[1,0]]]*2),z0=50)
 ask(text(a),'deembed',left=text(singular),right=text(a),reject=True)
 for token in ['NaN','Inf']:
  ask('# Hz S RI R 50\n1 '+token+' 0\n','dump',ports=1,reject=True)
 one=rf.Network(f=[1,2,3],s=np.array([0.,1.,1.2],dtype=complex).reshape(3,1,1),z0=50)
 def band(lo,hi,metric,maxval,status,max_details=8):
  out=ask(text(one),'band-check',limits=[dict(metric=metric,start_hz=lo,end_hz=hi,input=0,output=0,maximum=maxval)],max_details=max_details)
  assert out['status']==status,(out,status);checks.append(dict(label=f'analytic {metric} [{lo},{hi}]',status=status))
  return out
 band(1,2,'reflection_magnitude',1,'pass')
 band(1,3,'reflection_magnitude',1,'fail',max_details=0)
 band(0,3,'reflection_magnitude',1,'fail')
 band(1.3,1.5,'reflection_magnitude',1,'inconclusive')
 band(1,2,'vswr',100,'fail')
 band(3,3,'vswr',100,'inconclusive')
 for transmissions,state in [([.5,0.],'fail'),([0.,0.],'inconclusive')]:
  s=np.zeros((2,2,2),dtype=complex);s[:,1,0]=transmissions
  out=ask(text(rf.Network(f=[1,2],s=s,z0=50)),'ripple-check',start_hz=1,end_hz=2,input=0,output=1,maximum_ripple_db=1.)
  assert out['status']==state,out;checks.append(dict(label='analytic zero-transmission ripple',status=state))
except Exception as e:failure=e
finally:
 host.stdin.close();host.wait(timeout=10)
 result=dict(complete=failure is None,failure=repr(failure) if failure else None,requests=len(raw),checks=checks,raw=raw,
 versions=dict(numpy=np.__version__,scikit_rf=rf.__version__),sourceSHA256={k:hashlib.sha256((ROOT/k).read_bytes()).hexdigest() for k in ['complex.mbt','matrix.mbt','cascade.mbt','conversion.mbt','mixed_mode.mbt','bands.mbt','ripple.mbt','tools/verify-repair05.py']})
 args.evidence.write_text(json.dumps(result,indent=2)+'\n',encoding='utf-8');print(json.dumps({k:result[k] for k in ['complete','failure','requests','checks','versions']},indent=2))
if failure:raise failure
